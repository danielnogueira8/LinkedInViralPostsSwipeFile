import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourceDir = path.join(root, "mcp-apps", "swipe-file");
const template = await readFile(path.join(sourceDir, "index.html"), "utf8");
const result = await build({
  entryPoints: [path.join(sourceDir, "app.ts")],
  bundle: true,
  format: "iife",
  minify: true,
  platform: "browser",
  target: ["es2022"],
  write: false,
});
const javascript = result.outputFiles[0].text.replaceAll("</script", "<\\/script");
const html = template.replace(
  "<!-- APP_SCRIPT -->",
  `<script>${javascript}</script>`,
);
const generated =
  "// Generated by scripts/build-mcp-swipe-app.mjs. Do not edit directly.\n" +
  `export const SWIPE_FILE_APP_HTML = ${JSON.stringify(html)};\n`;
await writeFile(
  path.join(root, "lib", "mcp", "swipe-file-app.generated.ts"),
  generated,
);
